-- The schema as of the first Flyway migration. Postgres only: the default
-- local profile uses in-memory H2 with Hibernate creating the tables.
--
-- Started from what Hibernate generates for the entities, then:
--   * readable constraint names
--   * NOT NULL where the app always sets a value
--   * indexes on the foreign keys that queries filter by (Postgres doesn't
--     create those by itself)
--   * CHECK and EXCLUDE constraints the database enforces whatever the app does
--
-- Hibernate checks on startup that the entities match these tables
-- (ddl-auto=validate). From now on, change the schema with a new
-- V2__..., V3__... file; never edit this one once it has run anywhere.

-- For the exclusion constraint on time_slot (= on court_id inside a GiST index)
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE organisation (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(255) NOT NULL,
    description   varchar(255),
    contact_email varchar(255)
);

CREATE TABLE app_user (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       varchar(255) NOT NULL,
    email           varchar(255) NOT NULL,
    password_hash   varchar(255) NOT NULL,
    role            varchar(255) NOT NULL,
    -- The organisation an ORG_ADMIN manages; null for everyone else
    organisation_id bigint,
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_role CHECK (role IN ('PUBLIC_USER', 'ORG_ADMIN', 'SUPER_ADMIN')),
    CONSTRAINT fk_app_user_organisation FOREIGN KEY (organisation_id) REFERENCES organisation (id)
);

CREATE TABLE venue (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(255) NOT NULL,
    address         varchar(255) NOT NULL,
    organisation_id bigint NOT NULL,
    CONSTRAINT fk_venue_organisation FOREIGN KEY (organisation_id) REFERENCES organisation (id)
);
CREATE INDEX idx_venue_organisation ON venue (organisation_id);

CREATE TABLE court (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(255) NOT NULL,
    sport_type      varchar(255) NOT NULL,
    capacity        integer,
    venue_id        bigint NOT NULL,
    -- The court this one is part of (a half's full hall); one level deep
    parent_court_id bigint,
    CONSTRAINT fk_court_venue FOREIGN KEY (venue_id) REFERENCES venue (id),
    CONSTRAINT fk_court_parent FOREIGN KEY (parent_court_id) REFERENCES court (id),
    CONSTRAINT ck_court_not_own_parent CHECK (parent_court_id IS NULL OR parent_court_id <> id)
);
CREATE INDEX idx_court_venue ON court (venue_id);
CREATE INDEX idx_court_parent ON court (parent_court_id);

CREATE TABLE time_slot (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id   bigint NOT NULL,
    start_time timestamp(6) NOT NULL,
    end_time   timestamp(6) NOT NULL,
    status     varchar(255) NOT NULL,
    -- Optimistic lock (@Version), the second layer against double booking
    version    bigint NOT NULL DEFAULT 0,
    CONSTRAINT fk_time_slot_court FOREIGN KEY (court_id) REFERENCES court (id),
    CONSTRAINT ck_time_slot_status CHECK (status IN ('AVAILABLE', 'BOOKED', 'BLOCKED', 'UNAVAILABLE')),
    CONSTRAINT ck_time_slot_ends_after_start CHECK (end_time > start_time),
    -- A court can never have two slots whose times overlap (back-to-back is
    -- fine: ranges are [start, end)). Slot generation already skips overlaps;
    -- this makes the database refuse them too, even if two admins generate
    -- at once or someone inserts rows by hand.
    CONSTRAINT ex_time_slot_no_overlap EXCLUDE USING gist (
        court_id WITH =,
        tsrange(start_time, end_time) WITH &&
    )
);
-- Browsing a court's slots, and finding overlapping slots on related courts
CREATE INDEX idx_court_start ON time_slot (court_id, start_time);

CREATE TABLE booking_series (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT fk_booking_series_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);

CREATE TABLE booking (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_slot_id bigint NOT NULL,
    user_id      bigint NOT NULL,
    series_id    bigint,
    booked_at    timestamp(6) NOT NULL,
    status       varchar(255) NOT NULL,
    -- The third layer against double booking: one booking per slot, whatever
    -- the application does
    CONSTRAINT uq_booking_time_slot UNIQUE (time_slot_id),
    CONSTRAINT ck_booking_status CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    CONSTRAINT fk_booking_time_slot FOREIGN KEY (time_slot_id) REFERENCES time_slot (id),
    CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT fk_booking_series FOREIGN KEY (series_id) REFERENCES booking_series (id)
);
CREATE INDEX idx_booking_user ON booking (user_id);
CREATE INDEX idx_booking_series ON booking (series_id);

CREATE TABLE waitlist_entry (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_slot_id bigint NOT NULL,
    user_id      bigint NOT NULL,
    joined_at    timestamp(6) NOT NULL,
    -- Also serves lookups by time_slot_id (it's the first column)
    CONSTRAINT uq_waitlist_slot_user UNIQUE (time_slot_id, user_id),
    CONSTRAINT fk_waitlist_time_slot FOREIGN KEY (time_slot_id) REFERENCES time_slot (id),
    CONSTRAINT fk_waitlist_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);
CREATE INDEX idx_waitlist_user ON waitlist_entry (user_id);

CREATE TABLE notification (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL,
    message    varchar(500) NOT NULL,
    created_at timestamp(6) NOT NULL,
    -- null until the user has seen it
    read_at    timestamp(6),
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);
CREATE INDEX idx_notification_user ON notification (user_id, created_at);
